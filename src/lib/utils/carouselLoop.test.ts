import { describe, expect, it } from 'vitest';
import { copiesNeeded, rebaseBefore, wrapOffset } from './carouselLoop';

describe('wrapOffset', () => {
	it('тримає позицію в межах однієї копії', () => {
		expect(wrapOffset(0, 100)).toBe(0);
		expect(wrapOffset(99, 100)).toBe(99);
		expect(wrapOffset(100, 100)).toBe(0);
		expect(wrapOffset(250, 100)).toBe(50);
	});

	it('від’ємну позицію заводить з іншого боку', () => {
		// Пружне доскролювання за лівий край дає саме від’ємні значення, а `%` у
		// JavaScript лишає їх від’ємними — стрічка стрибнула б за початок доріжки.
		expect(wrapOffset(-10, 100)).toBe(90);
		expect(wrapOffset(-150, 100)).toBe(50);
	});

	it('без виміряної копії нічого не робить', () => {
		// Перший кадр: ширину ще не заміряно. Ділення на нуль дало б NaN, а NaN у
		// scrollLeft — це стрічка, що зникла.
		expect(wrapOffset(42, 0)).toBe(42);
	});
});

describe('copiesNeeded', () => {
	it('вузька стрічка в широкому вікні дістає стільки копій, щоб петля була можлива', () => {
		// Сім історій по ~2060 пікселів у вікні 1600 — рівно той випадок, на якому
		// стрічка впиралася в кінець і ставала.
		expect(copiesNeeded(1600, 2060)).toBe(3);
		// Дуже широкий монітор: однієї копії замало навіть на екран.
		expect(copiesNeeded(3000, 500)).toBe(8);
	});

	it('копія, ширша за вікно, все одно дістає запасну', () => {
		// Для самої петлі вистачило б двох: за правим краєм лишається ще майже ціла.
		// Третя — та, завдяки якій плавний рух від стрілки не впирається в кінець
		// доріжки й не мусить зводити позицію перед собою. Одна зайва копія семи
		// карток коштує менше, ніж смик на кожному другому натиску.
		expect(copiesNeeded(300, 5000)).toBe(3);
	});

	it('вікна ще немає — початкова пара', () => {
		// Нульова ширина вікна буває рівно один раз: між появою вузла й першим
		// розкладанням. Плодити копії наосліп нема сенсу — за мить приїде замір.
		expect(copiesNeeded(0, 5000)).toBe(2);
	});

	it('без виміряної копії лишається початкова пара', () => {
		expect(copiesNeeded(1600, 0)).toBe(2);
	});
});

describe('rebaseBefore', () => {
	it('мовчить, поки місця вистачає', () => {
		expect(rebaseBefore(1000, 800, 2000, 4000)).toBeNull();
	});

	it('переносить на копію назад, коли ціль вибігає за доріжку', () => {
		expect(rebaseBefore(3500, 800, 2000, 4000)).toBe(1500);
	});

	it('переносить уперед, коли ціль вибігає за початок', () => {
		expect(rebaseBefore(300, -800, 2000, 4000)).toBe(2300);
	});

	it('мовчить, коли перенесення саме вибігає за доріжку', () => {
		// Доріжка коротша за дві копії — переносити нікуди, і краще впертися в кінець,
		// ніж стрибнути в нікуди.
		expect(rebaseBefore(500, -800, 2000, 1000)).toBeNull();
	});

	it('без виміряної копії не переносить', () => {
		expect(rebaseBefore(500, 800, 0, 1000)).toBeNull();
	});
});
