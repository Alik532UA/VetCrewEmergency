/**
 * Арифметика нескінченної стрічки: де вона зараз і скільки копій вмісту потрібно.
 *
 * Стрічка повторює свій вміст і перескакує на одну копію назад, щойно проїхала її
 * всю. Копії однакові, тож перескок не видно — за умови, що він рівно на ширину
 * копії й що за правим краєм вікна лишається ще ціла копія, яку видно після нього.
 *
 * ## Чому це окремий файл
 *
 * Не заради чистоти: цю арифметику зламали один раз, і зламали тихо. Поріг
 * перескоку був записаний як «півтори половини доріжки» — число, яке на півсотні
 * карток проєкту-джерела лежить у межах досяжного, а на семи історіях цього сайту
 * опиняється ДАЛІ, ніж узагалі можна доїхати. Стрічка впиралася в кінець і ставала,
 * і виглядало це як «карусель глючить і довго підвантажує». Перевірити таке в
 * компоненті нема як — воно живе в межах вікна й вимірюваннях DOM; трьома чистими
 * функціями це перевіряється числами (`carouselLoop.test.ts`).
 */

/**
 * Зводить позицію в межі однієї копії: `[0, unit)`.
 *
 * Працює і для від'ємних значень — пружне доскролювання за лівий край дає саме їх,
 * а `%` у JavaScript від'ємне лишає від'ємним.
 */
export const wrapOffset = (value: number, unit: number): number =>
	unit > 0 ? ((value % unit) + unit) % unit : value;

/**
 * Скільки разів повторити вміст.
 *
 * Одна копія — щоб було що показати замість тієї, з якої стрічка перескочила. Друга
 * запасна — щоб плавний рух від стрілки не впирався в кінець доріжки й не мусив
 * зводити позицію перед собою. Менше двох не буває: без копії петлі немає зовсім.
 */
export const copiesNeeded = (viewportWidth: number, unitWidth: number): number =>
	unitWidth > 0 ? Math.max(2, Math.ceil(viewportWidth / unitWidth) + 2) : 2;

/**
 * Куди перенести позицію ПЕРЕД плавним рухом, щоб той не вибіг за доріжку.
 *
 * `null` означає «нікуди, місця вистачає». Перенести треба саме до руху: перескок
 * посеред плавної прокрутки обриває її на півдорозі, і це той самий смик, заради
 * якого все й переписувалося.
 */
export function rebaseBefore(
	scrollLeft: number,
	amount: number,
	unit: number,
	max: number
): number | null {
	const target = scrollLeft + amount;
	if (unit <= 0 || (target >= 0 && target <= max)) return null;
	const rebased = scrollLeft - Math.sign(amount) * unit;
	return rebased >= 0 && rebased <= max ? rebased : null;
}
