/**
 * Наскільки далеко сторінка від'їхала з-під шапки, числом 0..1.
 *
 * Одне число на дві речі, які шапка робить під час прокручування: проявляє власне
 * тло (угорі сторінки вона прозора, і знімок першого екрана йде під самий верх
 * вікна) і проявляє тінь під собою. Обидві беруть його з `--header-shadow`, який
 * `Header.svelte` пише в розмітку на кожному кадрі.
 *
 * Файл лишився від `tabWave.ts`, де ці ж дві величини рахували ще й форму
 * анімованої вкладки під активним пунктом. Вкладку прибрано на прохання автора —
 * разом із нею пішли `tabShape` і `TAB_HEIGHT`, а ці дві переїхали сюди під
 * власною назвою: «хвиля» більше нічого не описує.
 */

/**
 * Скільки пікселів має проїхати сторінка, щоб шапка стала непрозорою повністю.
 *
 * 120 — щоб перехід устиг статися в межах першого екрана й не тягнувся половину
 * сторінки. Це ж число документоване в PROJECT-CONTEXT § 4.14 як `--hero-band`.
 */
export const SETTLE_DISTANCE = 120;

export const clamp01 = (value: number) => Math.min(1, Math.max(0, value));
