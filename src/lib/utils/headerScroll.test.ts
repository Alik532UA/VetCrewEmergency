import { describe, expect, it } from 'vitest';
import { clamp01, SETTLE_DISTANCE } from './headerScroll';

/**
 * Те, що лишилося від `tabWave.test.ts` після прибирання анімованої вкладки.
 *
 * Геометрію хвилі перевіряли одинадцять тестів; самої хвилі більше немає, тож
 * вони пішли разом із нею. `clamp01` лишився: ним обмежується частка
 * прокручування, з якої шапка бере прозорість і тінь, а прокрутка приходить із
 * `window.scrollY` — значення, яке в браузері буває й від'ємним (пружне
 * доскролювання вгору на macOS та iOS), і більшим за будь-яку межу.
 */
describe('clamp01', () => {
	it('тримає кінці', () => {
		expect(clamp01(-0.5)).toBe(0);
		expect(clamp01(0)).toBe(0);
		expect(clamp01(0.5)).toBe(0.5);
		expect(clamp01(1)).toBe(1);
		expect(clamp01(42)).toBe(1);
	});

	it('пружне доскролювання вгору не дає від’ємної частки', () => {
		// Саме такий `scrollY` приходить, коли сторінку відтягують за верхній край.
		expect(clamp01(-80 / SETTLE_DISTANCE)).toBe(0);
	});
});

describe('SETTLE_DISTANCE', () => {
	it('перехід укладається в перший екран', () => {
		// Число живе ще й у прозі (PROJECT-CONTEXT § 4.14). Тут — лише його зміст:
		// шапка мусить устигнути стати непрозорою в межах першого екрана, а не
		// тягнути перехід через півсторінки.
		expect(SETTLE_DISTANCE).toBeGreaterThan(0);
		expect(SETTLE_DISTANCE).toBeLessThan(400);
	});
});
