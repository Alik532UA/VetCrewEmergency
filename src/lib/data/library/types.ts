import type { Locale } from '$lib/i18n/locales';

/** Двомовний рядок. Відповідність вимагає ТИП — окремого правила не треба. */
export type Localized = Record<Locale, string>;

/**
 * Стаття бібліотеки «Що робити, якщо…».
 *
 * Це НЕ енциклопедія. Людина відкриває таку сторінку з телефона, стоячи над
 * твариною, і їй треба за хвилину зрозуміти одне: втручатися чи ні. Тому
 * структура однакова в кожної статті й задана типом, а не звичаєм:
 *
 *   `answer` — відповідь одним реченням, до будь-яких подробиць;
 *   `blocks` — чотири питання в НЕЗМІННОМУ порядку (див. нижче);
 *   `story`  — реальний випадок, який показує, чим це закінчується;
 *   `related` — куди піти, якщо тварина виявилася іншою.
 *
 * Порядок блоків саме такий, бо він відповідає порядку рішень: спершу «чи це
 * взагалі проблема», потім «як зрозуміти, що проблема є», потім «чим я можу
 * нашкодити», і лише тоді «кому дзвонити». Зворотний порядок — той, у якому
 * людина спершу дзвонить, а потім забирає тварину додому.
 */
export interface LibraryArticle {
	/** Сегмент адреси. Стабільний назавжди: на нього посилаються інші статті. */
	slug: string;
	/** Значок на картці. Емодзі, як у джерелі матеріалу. */
	emoji: string;
	/** Заголовок картки — з трьох крапок, як питання, що продовжує «Що робити, якщо…». */
	title: Localized;
	/** Рядок на картці в переліку й на головній. */
	teaser: Localized;
	/** Відповідь ОДНИМ реченням. Перше, що людина читає на сторінці. */
	answer: Localized;
	blocks: {
		/** Чи потрібно втручатися? */
		intervene: Localized;
		/** Коли потрібна допомога? */
		whenHelp: Localized;
		/** Чого не можна робити? */
		never: Localized;
		/** Коли звертатися за нашою допомогою? */
		whenCall: Localized;
	};
	/** Реальна історія порятунку — коротко, одним абзацом. */
	story: Localized;
	/** Слаги схожих статей. Перевіряється інваріантом: чужих тут не буває. */
	related: readonly string[];
}
