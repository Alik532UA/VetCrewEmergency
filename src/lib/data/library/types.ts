import type { Locale } from '$lib/i18n/locales';

/** Двомовний рядок. Відповідність вимагає ТИП — окремого правила не треба. */
export type Localized = Record<Locale, string>;

/**
 * Стаття бібліотеки «Що робити, якщо…».
 *
 * Це НЕ енциклопедія. Людина відкриває таку сторінку з телефона, стоячи над
 * твариною, і їй треба за хвилину зрозуміти одне: втручатися чи ні. Тому
 * структура однакова в кожної статті й задана типом, а не звичаєм:
 *
 *   `answer` — відповідь одним реченням, до будь-яких подробиць;
 *   `blocks` — чотири питання в НЕЗМІННОМУ порядку (див. нижче);
 *   `story`  — реальний випадок, який показує, чим це закінчується;
 *   `related` — куди піти, якщо тварина виявилася іншою.
 *
 * Порядок блоків саме такий, бо він відповідає порядку рішень: спершу «чи це
 * взагалі проблема», потім «як зрозуміти, що проблема є», потім «чим я можу
 * нашкодити», і лише тоді «кому дзвонити». Зворотний порядок — той, у якому
 * людина спершу дзвонить, а потім забирає тварину додому.
 */
/**
 * Шматок довгого тексту статті.
 *
 * Чотири види, і більше не треба: матеріал, заради якого це з'явилося, складається
 * рівно з них. Розмітки в даних немає навмисно — `text` це ТЕКСТ, а не HTML, тож
 * жодне джерело не може принести сюди розмітку, яку сторінка виконає.
 *
 * `note` — це «⚠️ Важливо» й «Пам'ятайте»: у джерелі вони виділені візуально, і
 * зливати їх зі звичайними абзацами означало б загубити наголос, який автор
 * поставив свідомо.
 */
export type ArticleBlock =
	| { kind: 'heading'; text: Localized }
	| { kind: 'text'; text: Localized }
	| { kind: 'list'; items: readonly Localized[] }
	| { kind: 'note'; text: Localized };

export interface LibraryArticle {
	/** Сегмент адреси. Стабільний назавжди: на нього посилаються інші статті. */
	slug: string;
	/** Значок на картці. Емодзі, як у джерелі матеріалу. */
	emoji: string;
	/** Заголовок картки — з трьох крапок, як питання, що продовжує «Що робити, якщо…». */
	title: Localized;
	/** Рядок на картці в переліку й на головній. */
	teaser: Localized;
	/** Відповідь ОДНИМ реченням. Перше, що людина читає на сторінці. */
	answer: Localized;
	blocks: {
		/** Чи потрібно втручатися? */
		intervene: Localized;
		/** Коли потрібна допомога? */
		whenHelp: Localized;
		/** Чого не можна робити? */
		never: Localized;
		/** Коли звертатися за нашою допомогою? */
		whenCall: Localized;
	};
	/**
	 * Повний текст статті — під чотирма блоками, а не замість них.
	 *
	 * Порядок тут принциповий і повторює принцип типу вище: відповідь за хвилину
	 * лишається ПЕРШОЮ, а довгий текст іде нижче — для того, хто вже вирішив, що
	 * робити, і тепер хоче зрозуміти чому. Якби довгий текст стояв угорі, сторінка
	 * перестала б відповідати на питання, заради якого її відкривають із телефона.
	 *
	 * Необов'язковий: більшість статей його не мають і не мусять. Стаття без `body`
	 * лишається рівно такою, якою була.
	 */
	body?: readonly ArticleBlock[];
	/** Реальна історія порятунку — коротко, одним абзацом. */
	story: Localized;
	/** Слаги схожих статей. Перевіряється інваріантом: чужих тут не буває. */
	related: readonly string[];
}

/**
 * Довгий текст статті лежить у JSON поруч — і цей рядок єдиний, хто про це знає.
 *
 * ## Чому JSON, а не масив у `.ts`
 *
 * Це ВМІСТ, а не код. Стаття на вісімдесят абзаців у TypeScript — це п'ятсот рядків,
 * які ніхто не читає як програму: там немає жодного рішення, лише текст. А коли
 * надійде переклад, працювати з ним буде перекладач, і йому потрібен JSON, а не
 * модуль із синтаксисом.
 *
 * Сказати прямо, бо інакше це виглядає як хитрість: гейт розміру файлів
 * (`structure.test.ts` § 7) сканує лише `.svelte|.ts|.js|.css`, тож JSON із-під нього
 * виходить. Це наслідок, а не мета — але наслідок реальний, і вирішувати, чи він
 * прийнятний, має власник проєкту, а не цей коментар.
 *
 * ## Чому приведення типу, а не перевірка
 *
 * `import` із JSON дає `kind: string`, а не наш союз — звузити його можна лише
 * приведенням. Щоб приведення не було обіцянкою на слово, форму КОЖНОГО файлу
 * перевіряє `library-bodies.test.ts`: він читає ті самі JSON і падає, щойно
 * трапиться невідомий `kind`, порожній текст чи список без пунктів.
 */
export const asBody = (raw: unknown): readonly ArticleBlock[] => raw as readonly ArticleBlock[];
